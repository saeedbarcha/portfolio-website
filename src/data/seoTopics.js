export function skillToSlug(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/\.js/g, "js")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export function getSeoTopicBySlug(slug) {
  return seoTopics.find((topic) => topic.slug === slug) || null;
}

export function getSeoTopicForTech(tech) {
  if (!tech) return null;
  const needle = String(tech).trim().toLowerCase();
  return (
    seoTopics.find((topic) =>
      [topic.name, topic.slug, ...(topic.aliases || [])].some(
        (alias) => alias.toLowerCase() === needle || skillToSlug(alias) === skillToSlug(needle),
      ),
    ) || null
  );
}

export function getAllSeoKeywords() {
  const fromTopics = seoTopics.flatMap((topic) => [
    topic.name,
    `${topic.name} developer`,
    `hire ${topic.name} developer`,
  ]);
  return [...new Set(fromTopics)];
}
